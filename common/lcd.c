static uint16_t framebuffer[PIXELS];

static void emit(uint8_t cmd)
{
    PRDR = (uint8_t)(PRDR & ~16u);
    __asm__ volatile("synco" ::: "memory");
    LCD = cmd;
    __asm__ volatile("synco" ::: "memory");
    PRDR = (uint8_t)(PRDR | 16u);
    __asm__ volatile("synco" ::: "memory");
}
static void data(uint16_t pixel)
{
    LCD = pixel;
    __asm__ volatile("synco" ::: "memory");
}
void lcd_clear(uint16_t color)
{
    for(int i = 0; i < PIXELS; ++i) framebuffer[i] = color;
}
void lcd_rect(int x0, int y0, int x1, int y1, uint16_t color)
{
    if(x0 < 0) x0 = 0;
    if(y0 < 0) y0 = 0;
    if(x1 >= LCD_WIDTH) x1 = LCD_WIDTH - 1;
    if(y1 >= LCD_HEIGHT) y1 = LCD_HEIGHT - 1;
    if(x0 > x1 || y0 > y1) return;
    for(int y = y0; y <= y1; ++y)
        for(int x = x0; x <= x1; ++x)
            framebuffer[y * LCD_WIDTH + x] = color;
}
void lcd_text(int x, int y, const char *s, uint16_t color)
{
    for(int i = 0; s[i] && x + 8 <= LCD_WIDTH; ++i, x += 8) {
        unsigned c = (uint8_t)s[i];
        if(c < 32 || c >= 128) c = '?';
        for(int yy = 0; yy < 8; ++yy) {
            uint8_t bits = font8x8[c - 32][yy];
            for(int xx = 0; xx < 8; ++xx)
                if((bits & (0x80u >> xx)) &&
                   x + xx >= 0 && y + yy >= 0 && y + yy < LCD_HEIGHT)
                    framebuffer[(y + yy) * LCD_WIDTH + x + xx] = color;
        }
    }
}
void lcd_present(void (*poll)(void))
{
    emit(0x2a); data(0); data(0); data(2); data(15);
    emit(0x2b); data(0); data(40); data(1); data(103);
    emit(0x2c);
    for(unsigned i = 0; i < PIXELS; ++i) {
        data(framebuffer[i]);
        if(poll && (i & 511u) == 511u) poll();
    }
    emit(0x29);
}
